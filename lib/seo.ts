/** «Уборка снега» → «uborka-snega», «Нижний Новгород» → «nizhniy-novgorod». */
export function slugify(s: string): string {
  return s.toLowerCase().split('').map(c => TR[c] ?? c).join('')
    .replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 80);
}

