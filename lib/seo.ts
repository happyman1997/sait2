// ── Города: адрес латиницей и «в каком городе» ──

const IN_CITY: Record<string, string> = {
  'нижний новгород': 'в Нижнем Новгороде', 'великий новгород': 'в Великом Новгороде', 'ростов-на-дону': 'в Ростове-на-Дону',
  'набережные челны': 'в Набережных Челнах', 'старый оскол': 'в Старом Осколе', 'санкт-петербург': 'в Санкт-Петербурге',
  // Несклоняемые и мужского рода на «-ль» — правило дало бы ошибку.
  'сочи': 'в Сочи', 'тольятти': 'в Тольятти', 'ярославль': 'в Ярославле', 'ставрополь': 'в Ставрополе',
  'севастополь': 'в Севастополе', 'симферополь': 'в Симферополе'
};

/** «Москва» → «в Москве», «Химки» → «в Химках», «Казань» → «в Казани»; если правило не подходит — null. */
export function inCity(city: string): string | null {
  const c = city.trim();
  const k = c.toLowerCase();
  if (IN_CITY[k]) return IN_CITY[k];
  if (!/^[А-ЯЁ][а-яё-]+$/.test(c)) return null;           // составные названия без словаря — не склоняем
  if (/[оеиуюэ]$/.test(k) && !/[ыи]$/.test(k)) return null; // Одинцово, Сочи — без склонения
  if (/а$/.test(k)) return 'в ' + c.slice(0, -1) + 'е';
  if (/ь$/.test(k)) return 'в ' + c.slice(0, -1) + 'и';
  if (/[ыи]$/.test(k)) return 'в ' + c.slice(0, -1) + 'ах';
  if (/[бвгдзклмнпрстфхцчшщж]$/.test(k)) return 'в ' + c + 'е';
  return null;
}

/** Заголовок про город: «Подработка в Москве» или «Подработка — Одинцово», если склонение неизвестно. */
export const cityPhrase = (prefix: string, city: string) => { const p = inCity(city); return p ? prefix + ' ' + p : prefix + ' — ' + city; };

