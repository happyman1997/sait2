import type { Metadata } from 'next';
import Link from 'next/link';
import { Crumbs, JsonLd, SeoPage } from '@/components/seo/Seo';
import sty from '@/components/seo/Seo.module.css';
import { seasonOf, WORK_SEASONS, workById } from '@/lib/seo';
import { config } from '@/server/config';
import { currentUser } from '@/server/http';
import { breadcrumbsLd, SITE_NAME, todayLocal } from '@/server/seo';

export const dynamic = 'force-dynamic';

export const metadata: Metadata = {
  title: 'Найти рабочих на разовые работы рядом — без посредников и комиссии — ' + SITE_NAME,
  description: 'Уборка снега, покос травы, уборка территории, погрузка, благоустройство: разместите заказ бесплатно — исполнители рядом получат уведомление и откликнутся. Оплата напрямую, без комиссии.',
  alternates: { canonical: '/zakazchikam' }
};

// Сезонный блок: что сейчас заказывают и что скоро — заказчику, а не исполнителю. soon — подпись, когда сезон «скоро».
const SEASON_TEXT: Record<string, { title: string; note: string; soon: string }> = {
  Зима: { title: 'Зима: снег и наледь', note: 'Людей на снег лучше найти заранее: смену «по вызову после снегопада» можно назначить ещё до снега — бригаде придёт срочное уведомление.', soon: 'Скоро снег — найдите людей заранее' },
  Весна: { title: 'Весна: субботники и благоустройство', note: 'Бригаду можно нанять на один день или на несколько выходных подряд — одним заказом.', soon: 'Скоро весна — субботники и благоустройство' },
  Лето: { title: 'Лето: покос и уход за участком', note: 'Покос и полив удобно заказать серией — раз в неделю до конца сезона.', soon: 'Скоро лето — покос и уход за участком' },
  Осень: { title: 'Осень: листва и подготовка к зиме', note: 'Перед зимой удобно сделать всё за один выход: листву, уборку участка и подготовку к зиме.', soon: 'Скоро осень — листва и подготовка к зиме' }
};
const labels = (season: string) => (WORK_SEASONS.find(s => s[0] === season)?.[1] || []).map(id => workById(id)?.label).filter(Boolean) as string[];
const lower = (s: string) => s.charAt(0).toLowerCase() + s.slice(1);

const WHO: [string, string][] = [
  ['Частный дом и дача', 'Разовый заказ: почистить двор и крышу, скосить траву, убрать листву, помочь с переездом.'],
  ['ТСЖ и управляющие компании', 'Бригада на сезон: вызываете после каждого снегопада, каждый выход сдаётся и оплачивается отдельно.'],
  ['Магазины, кафе, склады', 'Вход, парковка и подъезды чистые к открытию; погрузка и разгрузка машин.'],
  ['Стройки и подрядчики', 'Разнорабочие на день: погрузка, уборка территории, вывоз мусора.'],
  ['Коттеджные посёлки и СНТ', 'Общие дороги и территория; жители могут заказывать работу на своих участках сами.']
];

const FAQ: [string, string][] = [
  ['Сколько это стоит?', 'Для заказчика — бесплатно: площадка не берёт комиссию и не держит деньги. Ставку исполнителю вы назначаете сами и платите ему напрямую.'],
  ['Кто выполняет работу?', 'Исполнители — частные лица и самозанятые, которые откликнулись на ваш заказ. «Арена Работ» — площадка: помогает найти людей и договориться, но сама работы не выполняет.'],
  ['Как платить?', 'Напрямую исполнителю — способом из заказа: наличными в день выхода, переводом на карту, самозанятому с чеком или безналом по договору.'],
  ['Как понять, кого нанимать?', 'У каждого откликнувшегося видны рейтинг, отзывы других заказчиков, число смен и невыходов, инвентарь и статус самозанятого, если исполнитель его проверил.'],
  ['Нужен ли договор?', 'Договор по заказу заключается в сервисе в момент найма: его условия — карточка заказа и договорённости в чате. Это гражданско-правовой договор, не трудовой.'],
  ['Можно ли заказать работы на крыше или на высоте?', 'Да. Предупредите об этом в заказе и укажите требования — например, допуск к работам на высоте: откликнутся те, у кого он есть.'],
  ['Как быстро найдутся люди?', 'Исполнители поблизости получают уведомление сразу после публикации заказа; срочный заказ приходит с пометкой «Срочная смена». Скорость зависит от района и ставки.']
];

/** Страница для заказчиков: зачем площадка, что можно заказать (сейчас — по сезону), как это работает, вопросы. */
export default async function ForCustomers() {
  const me = await currentUser();
  // Работодатель уже вошёл — сразу форма заказа; остальным — регистрация работодателя, после неё — тоже форма.
  const order = me?.role === 'employer' ? '/?new=1' : '/auth?role=employer&next=new';
  const { now, soon } = seasonOf(todayLocal());
  const s = SEASON_TEXT[now];
  const mail = config.supportEmail();
  const crumbs: [string, string][] = [['Главная', '/'], ['Заказчикам', '/zakazchikam']];
  const faqLd = {
    '@context': 'https://schema.org', '@type': 'FAQPage',
    mainEntity: FAQ.map(([q, a]) => ({ '@type': 'Question', name: q, acceptedAnswer: { '@type': 'Answer', text: a } }))
  };
  return (
    <SeoPage>
      <JsonLd data={breadcrumbsLd(crumbs)} />
      <JsonLd data={faqLd} />
      <Crumbs items={[crumbs[0], ['Заказчикам']]} />
      <h1 className={sty.h1}>Рабочие на разовые смены рядом с вашим объектом</h1>
      <p className={sty.lead}>
        Без посредников и комиссии. Разместите заказ за пару минут — исполнители поблизости получат уведомление и откликнутся.
        Вы выбираете, кого нанять, договариваетесь в чате и платите напрямую.
      </p>
      <div className={sty.actions}>
        <Link href={order} className="btn btn-primary">Разместить заказ бесплатно</Link>
        <a href="#kak" className="btn btn-secondary">Как это работает</a>
      </div>

      <section className={sty.season} aria-label="Сезон">
        <h2>{s.title}</h2>
        <p><b>Работы сезона:</b> {labels(now).map(lower).join(', ')}.</p>
        <p className={sty.seasonNote}>{s.note}</p>
        {soon && <p className={sty.seasonSoon}><b>{SEASON_TEXT[soon].soon}:</b> {labels(soon).map(lower).join(', ')}.</p>}
      </section>

      <h2 className={sty.h2} id="kak">Как это работает</h2>
      <ol className={sty.steps}>
        <li><b>Опишите задачу.</b> Что сделать, где, когда, сколько людей и какая оплата. Адрес частного дома увидит только тот, кого вы наймёте.</li>
        <li><b>Исполнители откликнутся.</b> Уведомление приходит тем, кто рядом. У каждого видны рейтинг, отзывы, число смен и невыходов.</li>
        <li><b>Наймите подходящих.</b> Откроется чат с каждым. Нужно несколько человек — назначьте старшего, он сдаст работу за всех.</li>
        <li><b>Примите работу и заплатите.</b> Фото до и после — в чате заказа; оплата — напрямую исполнителю, способом из заказа.</li>
      </ol>

      <h2 className={sty.h2}>Что можно заказать</h2>
      {WORK_SEASONS.map(([season]) => (
        <p key={season} className={sty.text}><b>{season}:</b> {labels(season).map(lower).join(', ')}.</p>
      ))}
      <p className={sty.muted}>Нет подходящего — впишите свой вид работ, когда будете размещать заказ.</p>

      <h2 className={sty.h2}>Кому подходит</h2>
      <ul className={sty.who}>
        {WHO.map(([t, d]) => <li key={t}><b>{t}</b><span>{d}</span></li>)}
      </ul>

      <h2 className={sty.h2}>Почему это удобно</h2>
      <ul className={sty.list}>
        <li>Бесплатно: площадка не берёт комиссию и не держит деньги.</li>
        <li>Видно, кого нанимаете: рейтинг, отзывы, невыходы; самозанятому можно платить с чеком.</li>
        <li>Бригада со старшим — он сдаёт работу за всех.</li>
        <li>Смены «по вызову после снегопада» и выходы на весь сезон одним заказом.</li>
        <li>Срочный заказ приходит исполнителям с пометкой «Срочная смена».</li>
      </ul>

      <h2 className={sty.h2}>Частые вопросы</h2>
      <div className={sty.faq}>
        {FAQ.map(([q, a]) => <div key={q}><h3>{q}</h3><p>{a}</p></div>)}
      </div>

      <p className={sty.help}>
        <b>Первый заказ поможем разместить.</b> Напишите на <a href={'mailto:' + mail + '?subject=' + encodeURIComponent('Помогите разместить заказ')}>{mail}</a>:
        что нужно сделать, где и когда — подскажем, как оформить.
      </p>

      <div className={sty.cta}>
        <h2>Нужны люди на смену?</h2>
        <p>Разместите заказ — бесплатно; исполнители рядом получат уведомление.</p>
        <Link href={order} className="btn">Разместить заказ</Link>
      </div>
    </SeoPage>
  );
}
